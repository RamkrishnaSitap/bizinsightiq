# 6. Plotly Visualizations for Segmentation
# ---------------------------------------------------------------------------

def create_elbow_silhouette_chart(eval_df: pd.DataFrame) -> go.Figure:
    """Create a dual-axis diagnostic chart showing Inertia (Elbow) and Silhouette Score."""
    if eval_df.empty:
        fig = go.Figure()
        fig.update_layout(title="No evaluation data available")
        return fig

    fig = make_subplots(specs=[[{"secondary_y": True}]])

    # Inertia line (Elbow)
    fig.add_trace(
        go.Scatter(
            x=eval_df["k"],
            y=eval_df["Inertia"],
            name="Inertia (Elbow)",
            mode="lines+markers",
            marker=dict(size=8, color="#2b6cb0"),
            line=dict(width=3, color="#2b6cb0"),
        ),
        secondary_y=False,
    )

    # Silhouette score line
    if "SilhouetteScore" in eval_df.columns and not eval_df["SilhouetteScore"].isna().all():
        fig.add_trace(
            go.Scatter(
                x=eval_df["k"],
                y=eval_df["SilhouetteScore"],
                name="Silhouette Score",
                mode="lines+markers",
                marker=dict(size=8, color="#d69e2e"),
                line=dict(width=3, color="#d69e2e", dash="dash"),
            ),
            secondary_y=True,
        )

    fig.update_layout(
        title="<b>K-Means Cluster Diagnostics (Elbow Method & Silhouette Score)</b>",
        xaxis=dict(title="Number of Clusters (k)", tickmode="linear", dtick=1),
        hovermode="x unified",
        template="plotly_white",
        margin=dict(l=40, r=40, t=50, b=40),
        legend=dict(orientation="h", yanchor="bottom", y=1.02, xanchor="right", x=1),
    )
    fig.update_yaxes(title_text="Inertia (Within-Cluster Sum of Squares)", secondary_y=False)
    fig.update_yaxes(title_text="Silhouette Score", secondary_y=True, range=[0.0, 1.0])

    return fig


def create_pca_cluster_chart(
    pca_df: pd.DataFrame,
    pca_variance_ratio: Tuple[float, float],
) -> go.Figure:
    """Create a 2D scatter plot projecting multi-dimensional clusters onto principal components."""
    if pca_df.empty:
        fig = go.Figure()
        fig.update_layout(title="No cluster projection data available")
        return fig

    # Convert Cluster to categorical string for discrete color mapping
    plot_data = pca_df.copy()
    plot_data["ClusterLabel"] = plot_data["Cluster"].apply(lambda c: f"Cluster {c}")

    fig = px.scatter(
        plot_data,
        x="PC1",
        y="PC2",
        color="ClusterLabel",
        hover_data=["CustomerID", "Recency", "Frequency", "MonetaryValue", "TotalProfit"],
        title="<b>2D Customer Cluster Projection (Principal Component Analysis)</b>",
        labels={
            "PC1": f"Principal Component 1 ({pca_variance_ratio[0]}% variance)",
            "PC2": f"Principal Component 2 ({pca_variance_ratio[1]}% variance)",
            "ClusterLabel": "Assigned Segment",
        },
        template="plotly_white",
        color_discrete_sequence=px.colors.qualitative.Bold,
    )
    fig.update_traces(marker=dict(size=9, opacity=0.85, line=dict(width=1, color="DarkSlateGrey")))
    fig.update_layout(margin=dict(l=40, r=40, t=50, b=40))
    return fig


def create_cluster_profile_bar_chart(profile_df: pd.DataFrame) -> go.Figure:
    """Create grouped bar chart comparing mean monetary value and profit by cluster."""
    if profile_df.empty:
        fig = go.Figure()
        fig.update_layout(title="No profile data available")
        return fig

    cluster_names = [f"Cluster {c}" for c in profile_df["Cluster"]]

    fig = go.Figure(
        data=[
            go.Bar(name="Mean Sales ($)", x=cluster_names, y=profile_df["MeanSales"], marker_color="#3182ce"),
            go.Bar(name="Mean Profit ($)", x=cluster_names, y=profile_df["MeanProfit"], marker_color="#38a169"),
        ]
    )
    fig.update_layout(
        barmode="group",
        title="<b>Mean Revenue & Profit Comparison by Segment</b>",
        xaxis_title="Customer Segment",
        yaxis_title="Amount ($)",
        template="plotly_white",
        margin=dict(l=40, r=40, t=50, b=40),
        legend=dict(orientation="h", yanchor="bottom", y=1.02, xanchor="right", x=1),
    )
    return fig
