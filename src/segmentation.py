"""
AI/ML Customer Segmentation Engine for BizInsightIQ.

Provides framework-agnostic customer RFM/behavioral aggregation, feature scaling,
K-Means unsupervised clustering, silhouette and elbow diagnostics, cluster profiling,
and Plotly visual projections.
"""

from typing import Dict, Any, List, Optional, Tuple, Union
import pandas as pd
import numpy as np
from sklearn.preprocessing import StandardScaler
from sklearn.cluster import KMeans
from sklearn.metrics import silhouette_score
from sklearn.decomposition import PCA
import plotly.express as px
import plotly.graph_objects as go
from plotly.subplots import make_subplots


DEFAULT_FEATURE_COLS = [
    "Recency",
    "Frequency",
    "MonetaryValue",
    "TotalProfit",
    "AvgDiscount",
    "TotalQuantity",
]


def _validate_raw_columns(df: pd.DataFrame, required: List[str]) -> None:
    """Ensure required columns exist in input DataFrame."""
    if not isinstance(df, pd.DataFrame):
        raise TypeError(f"Expected pandas DataFrame, got {type(df).__name__}")
    missing = [c for c in required if c not in df.columns]
    if missing:
        raise ValueError(f"Missing required columns for segmentation: {', '.join(missing)}")


# ---------------------------------------------------------------------------
# 1. Customer-Level Feature Aggregation
# ---------------------------------------------------------------------------

def aggregate_customer_features(
    df: pd.DataFrame,
    reference_date: Optional[Union[str, pd.Timestamp]] = None,
) -> pd.DataFrame:
    """
    Aggregate transaction-level records into one observation per customer.

    Computes RFM (Recency, Frequency, Monetary Value) and behavioral features:
    - Recency: Elapsed days between customer's latest transaction and the reference date.
    - Frequency: Count of transaction rows associated with customer.
      (NOTE: Transaction-row count serves as a proxy for purchase frequency
      due to the absence of a distinct OrderID in the source schema).
    - MonetaryValue: Cumulative sales amount attributed to the customer.
    - TotalProfit: Cumulative net profit generated by the customer.
    - AvgDiscount: Mean promotional discount rate received by customer.
    - TotalQuantity: Total product units purchased.
    - AvgOrderValue: MonetaryValue / Frequency.
    - ProfitMarginPct: (TotalProfit / MonetaryValue) * 100.

    Parameters
    ----------
    df : pd.DataFrame
        Sales transactions DataFrame.
    reference_date : Optional[Union[str, pd.Timestamp]], default None
        Fixed benchmark date for recency calculation. If None, defaults to
        one day after the maximum valid transaction date in the dataset to
        guarantee 100% deterministic, reproducible outputs across executions.

    Returns
    -------
    pd.DataFrame
        Customer-level aggregated DataFrame with one record per CustomerID.
    """
    _validate_raw_columns(df, ["CustomerID", "OrderDate", "Sales", "Profit", "Quantity", "Discount"])

    empty_cols = [
        "CustomerID", "Recency", "Frequency", "MonetaryValue",
        "TotalProfit", "AvgDiscount", "TotalQuantity",
        "AvgOrderValue", "ProfitMarginPct"
    ]
    if df.empty:
        return pd.DataFrame(columns=empty_cols)

    data = df.copy()
    data["ParsedDate"] = pd.to_datetime(data["OrderDate"], errors="coerce", format="mixed")
    data = data.dropna(subset=["ParsedDate"])

    if data.empty:
        return pd.DataFrame(columns=empty_cols)

    # Establish reference date for deterministic recency
    if reference_date is None:
        benchmark_date = data["ParsedDate"].max() + pd.Timedelta(days=1)
    else:
        benchmark_date = pd.to_datetime(reference_date, errors="coerce", format="mixed")
        if pd.isna(benchmark_date):
            raise ValueError(f"Invalid reference_date provided: {reference_date}")

    # Group by CustomerID
    customer_df = data.groupby("CustomerID").agg(
        LatestDate=("ParsedDate", "max"),
        Frequency=("Sales", "count"),
        MonetaryValue=("Sales", "sum"),
        TotalProfit=("Profit", "sum"),
        AvgDiscount=("Discount", "mean"),
        TotalQuantity=("Quantity", "sum"),
    ).reset_index()

    # Calculate Recency in days
    customer_df["Recency"] = (benchmark_date - customer_df["LatestDate"]).dt.days
    customer_df = customer_df.drop(columns=["LatestDate"])

    # Derived business metrics
    customer_df["AvgOrderValue"] = np.where(
        customer_df["Frequency"] > 0,
        customer_df["MonetaryValue"] / customer_df["Frequency"],
        0.0
    ).round(2)

    customer_df["ProfitMarginPct"] = np.where(
        customer_df["MonetaryValue"] > 0,
        (customer_df["TotalProfit"] / customer_df["MonetaryValue"]) * 100.0,
        0.0
    ).round(2)

    customer_df["MonetaryValue"] = customer_df["MonetaryValue"].round(2)
    customer_df["TotalProfit"] = customer_df["TotalProfit"].round(2)
    customer_df["AvgDiscount"] = customer_df["AvgDiscount"].round(4)
    customer_df["TotalQuantity"] = customer_df["TotalQuantity"].astype(int)
    customer_df["Recency"] = customer_df["Recency"].astype(int)
    customer_df["Frequency"] = customer_df["Frequency"].astype(int)

    return customer_df.sort_values("CustomerID").reset_index(drop=True)


# ---------------------------------------------------------------------------
# 2. Feature Preparation & Normalization
# ---------------------------------------------------------------------------

def prepare_features_for_clustering(
    customer_df: pd.DataFrame,
    feature_cols: Optional[List[str]] = None,
) -> Tuple[np.ndarray, StandardScaler, List[str]]:
    """
    Prepare, clean, and standardize customer features for unsupervised clustering.

    Parameters
    ----------
    customer_df : pd.DataFrame
        Customer-level aggregated DataFrame.
    feature_cols : Optional[List[str]], default None
        List of numeric features to include. If None, uses DEFAULT_FEATURE_COLS.

    Returns
    -------
    Tuple[np.ndarray, StandardScaler, List[str]]
        Standardized feature array, fitted StandardScaler, and active feature names.
    """
    if not isinstance(customer_df, pd.DataFrame):
        raise TypeError(f"Expected pandas DataFrame, got {type(customer_df).__name__}")

    if len(customer_df) < 2:
        raise ValueError(f"Insufficient customer observations ({len(customer_df)}) for feature scaling. Minimum 2 required.")

    if feature_cols is None:
        feature_cols = [c for c in DEFAULT_FEATURE_COLS if c in customer_df.columns]
    else:
        missing = [c for c in feature_cols if c not in customer_df.columns]
        if missing:
            raise ValueError(f"Specified feature columns missing from customer data: {', '.join(missing)}")

    # Ensure no ID column leaks into numerical features
    active_features = [c for c in feature_cols if c != "CustomerID"]
    if not active_features:
        raise ValueError("No valid numerical features selected for clustering.")

    X = customer_df[active_features].copy()

    # Handle non-finite or missing values safely
    X = X.replace([np.inf, -np.inf], np.nan)
    for col in X.columns:
        if X[col].isnull().any():
            median_val = X[col].median()
            X[col] = X[col].fillna(median_val if not np.isnan(median_val) else 0.0)

    # Check zero-variance features
    valid_features = []
    for col in active_features:
        if X[col].std() == 0.0:
            continue  # Drop zero-variance feature to prevent division by zero in scaling
        valid_features.append(col)

    if len(valid_features) < 1:
        raise ValueError("All selected features have zero variance. Cannot perform clustering.")

    scaler = StandardScaler()
    X_scaled = scaler.fit_transform(X[valid_features])

    return X_scaled, scaler, valid_features


# ---------------------------------------------------------------------------
# 3. K-Means Clustering & PCA Projection
# ---------------------------------------------------------------------------

def perform_kmeans_clustering(
    customer_df: pd.DataFrame,
    n_clusters: int = 4,
    random_state: int = 42,
    feature_cols: Optional[List[str]] = None,
) -> Dict[str, Any]:
    """
    Execute K-Means clustering on customer features and generate a 2D PCA projection.

    Parameters
    ----------
    customer_df : pd.DataFrame
        Customer-level aggregated data.
    n_clusters : int, default 4
        Number of clusters to form. Must be >= 2 and < number of customers.
    random_state : int, default 42
        Seed for reproducible centroid initialization.
    feature_cols : Optional[List[str]]
        Features to include in clustering.

    Returns
    -------
    Dict[str, Any]
        Dictionary containing clustered DataFrame, model, scaler, inertia,
        silhouette score, and PCA 2D coordinates.
    """
    if customer_df.empty:
        raise ValueError("Cannot perform K-Means clustering on an empty DataFrame.")

    n_samples = len(customer_df)
    if n_clusters < 2:
        raise ValueError(f"Cluster count must be >= 2. Received: {n_clusters}")
    if n_clusters >= n_samples:
        raise ValueError(
            f"Requested cluster count ({n_clusters}) must be strictly less than customer count ({n_samples})."
        )

    X_scaled, scaler, active_features = prepare_features_for_clustering(
        customer_df, feature_cols=feature_cols
    )

    kmeans = KMeans(
        n_clusters=n_clusters,
        random_state=random_state,
        n_init=10,
        max_iter=300,
    )
    cluster_labels = kmeans.fit_predict(X_scaled)

    # Calculate evaluation metrics
    inertia = float(kmeans.inertia_)
    if len(set(cluster_labels)) > 1 and n_samples > n_clusters:
        sil_score = float(silhouette_score(X_scaled, cluster_labels))
    else:
        sil_score = None

    # Attach cluster assignments
    clustered_df = customer_df.copy()
    clustered_df["Cluster"] = cluster_labels.astype(int)

    # Compute 2D PCA projection for visualization
    pca = PCA(n_components=2, random_state=random_state)
    pca_coords = pca.fit_transform(X_scaled)
    var_ratio = (float(pca.explained_variance_ratio_[0]), float(pca.explained_variance_ratio_[1]))

    pca_df = pd.DataFrame({
        "CustomerID": customer_df["CustomerID"],
        "PC1": pca_coords[:, 0].round(3),
        "PC2": pca_coords[:, 1].round(3),
        "Cluster": cluster_labels.astype(int),
        "Recency": customer_df["Recency"],
        "Frequency": customer_df["Frequency"],
        "MonetaryValue": customer_df["MonetaryValue"],
        "TotalProfit": customer_df["TotalProfit"],
        "AvgDiscount": customer_df["AvgDiscount"],
    })

    return {
        "clustered_df": clustered_df,
        "model": kmeans,
        "scaler": scaler,
        "feature_cols": active_features,
        "n_clusters": n_clusters,
        "inertia": round(inertia, 2),
        "silhouette_score": round(sil_score, 3) if sil_score is not None else None,
        "pca_df": pca_df,
        "pca_variance_ratio": (round(var_ratio[0] * 100, 1), round(var_ratio[1] * 100, 1)),
    }


# ---------------------------------------------------------------------------
# 4. Cluster Diagnostic Evaluation (Elbow & Silhouette Sweep)
# ---------------------------------------------------------------------------

def evaluate_cluster_candidates(
    customer_df: pd.DataFrame,
    k_min: int = 2,
    k_max: int = 8,
    random_state: int = 42,
    feature_cols: Optional[List[str]] = None,
) -> pd.DataFrame:
    """
    Evaluate candidate cluster counts using Inertia (Elbow) and Silhouette Scores.

    Parameters
    ----------
    customer_df : pd.DataFrame
        Customer-level data.
    k_min : int, default 2
        Minimum number of clusters to test.
    k_max : int, default 8
        Maximum number of clusters to test.
    random_state : int, default 42
        Random seed for reproducibility.

    Returns
    -------
    pd.DataFrame
        Diagnostics table with columns ['k', 'Inertia', 'SilhouetteScore'].
    """
    if customer_df.empty:
        return pd.DataFrame(columns=["k", "Inertia", "SilhouetteScore"])

    n_samples = len(customer_df)
    k_upper = min(k_max, n_samples - 1)
    if k_upper < k_min:
        return pd.DataFrame(columns=["k", "Inertia", "SilhouetteScore"])

    X_scaled, _, _ = prepare_features_for_clustering(customer_df, feature_cols=feature_cols)

    records = []
    for k in range(k_min, k_upper + 1):
        km = KMeans(n_clusters=k, random_state=random_state, n_init=10, max_iter=300).fit(X_scaled)
        labels = km.labels_

        sil = None
        if len(set(labels)) > 1 and n_samples > k:
            try:
                sil = float(silhouette_score(X_scaled, labels))
            except Exception:
                sil = None

        records.append({
            "k": k,
            "Inertia": round(float(km.inertia_), 2),
            "SilhouetteScore": round(sil, 3) if sil is not None else np.nan,
        })

    return pd.DataFrame(records)


# ---------------------------------------------------------------------------
# 5. Cluster Profiling & Neutral Persona Attribution
# ---------------------------------------------------------------------------

def generate_cluster_profiles(clustered_df: pd.DataFrame) -> pd.DataFrame:
    """
    Generate statistical summary profiles and neutral persona descriptions for each cluster.

    Parameters
    ----------
    clustered_df : pd.DataFrame
        Customer DataFrame containing 'Cluster' and numerical feature columns.

    Returns
    -------
    pd.DataFrame
        Summary table with customer counts, percentages, feature means, and neutral tags.
    """
    if clustered_df.empty or "Cluster" not in clustered_df.columns:
        return pd.DataFrame()

    total_customers = len(clustered_df)
    pop_median_sales = clustered_df["MonetaryValue"].median()
    pop_median_recency = clustered_df["Recency"].median()
    pop_median_discount = clustered_df["AvgDiscount"].median()

    profiles = []
    for cluster_id, grp in clustered_df.groupby("Cluster"):
        count = len(grp)
        pct = (count / total_customers) * 100.0

        mean_rec = float(grp["Recency"].mean())
        mean_freq = float(grp["Frequency"].mean())
        mean_monetary = float(grp["MonetaryValue"].mean())
        total_sales = float(grp["MonetaryValue"].sum())
        mean_profit = float(grp["TotalProfit"].mean())
        total_profit = float(grp["TotalProfit"].sum())
        mean_discount = float(grp["AvgDiscount"].mean())
        mean_qty = float(grp["TotalQuantity"].mean())

        margin_pct = (total_profit / total_sales * 100.0) if total_sales > 0 else 0.0

        # Construct data-grounded neutral descriptive tag
        tags = []
        if mean_monetary >= pop_median_sales * 1.5:
            tags.append("High Spend")
        elif mean_monetary < pop_median_sales * 0.7:
            tags.append("Low Spend")
        else:
            tags.append("Moderate Spend")

        if mean_discount > pop_median_discount * 1.3:
            tags.append("Discount-Oriented")

        if mean_rec > pop_median_recency * 1.4:
            tags.append("Lapsed / Inactive")
        elif mean_rec <= pop_median_recency * 0.7:
            tags.append("Recently Active")

        descriptive_tag = " • ".join(tags)

        profiles.append({
            "Cluster": int(cluster_id),
            "DescriptivePersona": descriptive_tag,
            "CustomerCount": count,
            "CustomerPct": round(pct, 1),
            "MeanRecencyDays": round(mean_rec, 1),
            "MeanFrequency": round(mean_freq, 1),
            "MeanSales": round(mean_monetary, 2),
            "TotalSales": round(total_sales, 2),
            "MeanProfit": round(mean_profit, 2),
            "TotalProfit": round(total_profit, 2),
            "MeanDiscountPct": round(mean_discount * 100.0, 1),
            "MeanUnits": round(mean_qty, 1),
            "ProfitMarginPct": round(margin_pct, 1),
        })

    profile_df = pd.DataFrame(profiles)
    return profile_df.sort_values("Cluster").reset_index(drop=True)


